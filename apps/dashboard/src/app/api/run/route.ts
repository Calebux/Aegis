/**
 * POST /api/run
 *
 * Accepts { task: string }, runs the Aegis multi-agent pipeline, and streams
 * progress back to the client via Server-Sent Events.
 *
 * Event shapes:
 *   { type: "log",          payload: { message: string, level: "info"|"success"|"error" } }
 *   { type: "agent_status", payload: { agent: AgentId, status: AgentStatus, spent?: number } }
 *   { type: "wallets",      payload: Record<AgentId, string> }
 *   { type: "complete",     payload: AegisReport }
 *   { type: "error",        payload: { message: string } }
 */

import { NextRequest } from "next/server";

export const dynamic = "force-dynamic";

type AgentId = "scout" | "ledger" | "signal" | "scribe";

// ── Helpers ───────────────────────────────────────────────────────────────────

/** Generate a valid-looking Stellar public key (G + 55 base32 chars). */
function genStellarKey(): string {
  const base32 = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
  let key = "G";
  for (let i = 0; i < 55; i++) {
    key += base32[Math.floor(Math.random() * base32.length)];
  }
  return key;
}

function sleep(ms: number): Promise<void> {
  return new Promise((r) => setTimeout(r, ms));
}

