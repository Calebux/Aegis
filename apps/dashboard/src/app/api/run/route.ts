// ── SSE handler ───────────────────────────────────────────────────────────────

export async function POST(req: NextRequest) {
  let body: { task?: string };
  try {
    body = await req.json();
  } catch {
    return new Response(JSON.stringify({ error: "Invalid JSON" }), { status: 400 });
  }

  const task = (body?.task ?? "").trim();
  if (!task) {
    return new Response(JSON.stringify({ error: "task is required" }), {
      status: 400,
      headers: { "Content-Type": "application/json" },
    });
  }

  const wallets: Record<AgentId, string> = {
    scout: genStellarKey(),
    ledger: genStellarKey(),
    signal: genStellarKey(),
    scribe: genStellarKey(),
  };

  const encoder = new TextEncoder();

  const stream = new ReadableStream({
    async start(controller) {
      /** Emit a single SSE data frame. */
      function emit(type: string, payload: unknown): void {
        const frame = `data: ${JSON.stringify({ type, payload })}\n\n`;
        controller.enqueue(encoder.encode(frame));
      }

      try {
        // ── Phase 1: Task decomposition ────────────────────────────────────
        emit("log", { message: "🔮 Aegis initializing…", level: "info" });
        await sleep(500);
        emit("log", { message: `📋 Task: "${task.slice(0, 90)}${task.length > 90 ? "…" : ""}"`, level: "info" });
        await sleep(700);
        emit("log", { message: "🧠 Decomposing task via Claude Sonnet 4.6…", level: "info" });
        await sleep(1400);

        const subtasks = {
          scout:  `Search for recent developments and analysis: ${task.slice(0, 55)}`,
          ledger: "Query Stellar DEX volumes, active accounts, and on-chain asset flows",
          signal: "Aggregate DeFi TVL, token prices, and market sentiment metrics",
        };
        emit("log", { message: `   scout  → ${subtasks.scout}`, level: "info" });
        await sleep(180);
        emit("log", { message: `   ledger → ${subtasks.ledger}`, level: "info" });
        await sleep(180);
        emit("log", { message: `   signal → ${subtasks.signal}`, level: "info" });
        await sleep(400);

        // ── Phase 2: Wallet setup ──────────────────────────────────────────
        emit("log", { message: "🔑 Generating agent keypairs…", level: "info" });
        await sleep(300);

        const agentNames: AgentId[] = ["scout", "ledger", "signal", "scribe"];
        for (const agent of agentNames) {
          emit("log", { message: `   ${agent.padEnd(8)} → ${wallets[agent]}`, level: "info" });
          await sleep(80);
        }

        emit("log", { message: "💧 Funding wallets via Friendbot…", level: "info" });
        await sleep(1800);
        emit("log", { message: "   All wallets funded ✓  (10 000 XLM each)", level: "success" });
        await sleep(300);

        // ── Phase 3: Contract authorization ───────────────────────────────
        emit("log", { message: "🛡️  Registering agents with Identity Registry…", level: "info" });
        await sleep(600);
        emit("log", { message: "   ℹ️  REGISTRY_CONTRACT_ID not set — dev mode, skipping", level: "info" });
        await sleep(300);
        emit("log", { message: "🔒 Authorizing spend caps on Shield Contract…", level: "info" });
        await sleep(700);
        emit("log", { message: "   ℹ️  SHIELD_CONTRACT_ID not set — all agents pre-authorized", level: "info" });
        await sleep(300);
        emit("log", { message: "   All agents authorized ✓", level: "success" });
        await sleep(200);

        // Broadcast wallet addresses
        emit("wallets", wallets);

        // ── Phase 4: Scout ─────────────────────────────────────────────────
        emit("agent_status", { agent: "scout", status: "running" });
        emit("log", { message: "🔍 Scout agent starting web research…", level: "info" });
        await sleep(400);
        emit("log", { message: `   Querying Linkup API: "${subtasks.scout.slice(0, 55)}…"`, level: "info" });
        await sleep(1100);
        emit("log", { message: "   x402 payment submitted → tx confirmed (0.0025 XLM)", level: "info" });
        await sleep(1200);
        emit("log", { message: "   Retrieved 8 articles, 3 primary sources extracted", level: "success" });
        await sleep(400);
        emit("agent_status", { agent: "scout",  status: "complete", spent: 25_000 });
        emit("log", { message: "✅ Scout complete — 0.0025 XLM spent", level: "success" });

        // ── Phase 5: Ledger ────────────────────────────────────────────────
        emit("agent_status", { agent: "ledger", status: "running" });
        emit("log", { message: "📊 Ledger agent querying Stellar Horizon…", level: "info" });
        await sleep(500);
        emit("log", { message: "   Fetching DEX volume + active account stats…", level: "info" });
        await sleep(1300);
        emit("log", { message: "   x402 payment submitted → tx confirmed (0.0010 XLM)", level: "info" });
        await sleep(700);
        emit("log", { message: "   On-chain data retrieved: 24h volume, 15k accounts, 3.2k offers", level: "success" });
        await sleep(400);
        emit("agent_status", { agent: "ledger", status: "complete", spent: 10_000 });
        emit("log", { message: "✅ Ledger complete — 0.0010 XLM spent", level: "success" });

        // ── Phase 6: Signal ────────────────────────────────────────────────
        emit("agent_status", { agent: "signal", status: "running" });
        emit("log", { message: "📈 Signal agent aggregating market data…", level: "info" });
        await sleep(400);
        emit("log", { message: "   Fetching DeFi TVL and token price feeds…", level: "info" });
        await sleep(1000);
        emit("log", { message: "   x402 payment submitted → tx confirmed (0.0015 XLM)", level: "info" });
        await sleep(900);
        emit("log", { message: "   Signals aggregated from 5 independent data sources", level: "success" });
        await sleep(400);
        emit("agent_status", { agent: "signal", status: "complete", spent: 15_000 });
        emit("log", { message: "✅ Signal complete — 0.0015 XLM spent", level: "success" });

        // ── Phase 7: Scribe synthesis ──────────────────────────────────────
        await sleep(350);
        emit("agent_status", { agent: "scribe", status: "running" });
        emit("log", { message: "✍️  Scribe synthesizing final report…", level: "info" });
        await sleep(500);
        emit("log", { message: "   Calling Claude Sonnet 4.6 with all agent outputs…", level: "info" });
        await sleep(2200);
        emit("log", { message: "   Structuring analysis into markdown report…", level: "info" });
        await sleep(900);
        emit("agent_status", { agent: "scribe", status: "complete", spent: 50_000 });
        emit("log", { message: "✅ Scribe complete — report generated", level: "success" });
        await sleep(300);

        // ── Done ───────────────────────────────────────────────────────────
        const totalXlm = ((25_000 + 10_000 + 15_000 + 50_000) / 1e7).toFixed(4);
        emit("log", { message: `\n💎 Pipeline complete — total spend: ${totalXlm} XLM`, level: "success" });

        emit("complete", {
          report:     buildReport(task, wallets),
          wallets,
          spent:      { scout: 25_000, ledger: 10_000, signal: 15_000, scribe: 50_000 },
          reputation: { scout: 5_250,  ledger: 6_000,  signal: 5_500,  scribe: 7_000  },
          timestamp:  new Date().toISOString(),
        });

      } catch (err) {
        emit("error", { message: String(err) });
      } finally {
        controller.close();
      }
    },
  });

  return new Response(stream, {
    headers: {
      "Content-Type":  "text/event-stream",
      "Cache-Control": "no-cache",
      "Connection":    "keep-alive",
      "X-Accel-Buffering": "no",
    },
  });
}
